function lines(parts) {
    return parts.join('\n') + '\n';
}

function replaceInText(text, before, after, label) {
    if (text.includes(after)) return text;
    if (!text.includes(before)) {
        throw new Error(`Patch anchor not found for ${label}`);
    }
    return text.replace(before, after);
}

function replaceByRegex(text, regex, replacement, successNeedle, label) {
    if (text.includes(successNeedle)) return text;
    if (!regex.test(text)) {
        throw new Error(`Patch anchor not found for ${label}`);
    }
    return text.replace(regex, replacement);
}

